export const findWargativeAssets = async (type, queryData) => {
  let filtered = curatedStockPhotos;

  if (queryData && queryData.query && queryData.query.trim() !== '') {
    const q = queryData.query.toLowerCase().trim();
    filtered = curatedStockPhotos.filter(
      (item) =>
        item.label.toLowerCase().includes(q) ||
        item.tags.some((tag) => tag.toLowerCase().includes(q))
    );
  }

  const assets = filtered.map((photo) => ({
    id: photo.id,
    type: 'ly.img.image',
    locale: 'en',
    label: photo.label,
    thumbUri: photo.thumb,
    size: {
      width: photo.width,
      height: photo.height
    },
    meta: {
      uri: photo.full
    },
    context: {
      sourceId: 'wargativeStock'
    },
    credits: {
      name: photo.credit,
      url: 'https://unsplash.com'
    }
  }));

  return {
    assets,
    total: assets.length,
    currentPage: 1,
    nextPage: undefined
  };
};
